local function _total(actor)
    return RechargeRecord.getTotalMoney(actor)
end

ConditionHandler:register(ConditionId.rehcarge["充值总金额>"], "充值总金额>", function(actor, param)
    return _total(actor) > tonumber(param)
end)
ConditionHandler:register(ConditionId.rehcarge["充值总金额>="], "充值总金额>=", function(actor, param)
    return _total(actor) >= tonumber(param)
end)
ConditionHandler:register(ConditionId.rehcarge["充值总金额=="], "充值总金额==", function(actor, param)
    return _total(actor) == tonumber(param)
end)
ConditionHandler:register(ConditionId.rehcarge["充值总金额<="], "充值总金额<=", function(actor, param)
    return _total(actor) <= tonumber(param)
end)
ConditionHandler:register(ConditionId.rehcarge["充值总金额<"], "充值总金额<", function(actor, param)
    return _total(actor) < tonumber(param)
end)
ConditionHandler:register(ConditionId.rehcarge["充值总金额~="], "充值总金额~=", function(actor, param)
    return _total(actor) ~= tonumber(param)
end)
